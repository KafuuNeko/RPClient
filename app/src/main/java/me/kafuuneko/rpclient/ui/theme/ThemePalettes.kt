/**
 * 低饱和 Material 色阶预设，明暗两套均覆盖容器与语义颜色。
 * - 由 Material Color Utilities 0.4.0 的 2021 标准色阶生成，无运行时依赖。
 * - 石墨采用中性色阶，其余采用柔和色调，避免大面积高饱和背景。
 */
internal fun presetColorScheme(palette: AppThemePalette, dark: Boolean): ColorScheme? =
    when (palette) {
        AppThemePalette.Sakura -> if (dark) SakuraDark else SakuraLight
        AppThemePalette.Forest -> if (dark) ForestDark else ForestLight
        AppThemePalette.Twilight -> if (dark) TwilightDark else TwilightLight
        AppThemePalette.Parchment -> if (dark) ParchmentDark else ParchmentLight
        AppThemePalette.Graphite -> if (dark) GraphiteDark else GraphiteLight
        else -> null
    }

